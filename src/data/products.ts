export type Category = 'supplements' | 'devices' | 'care' | 'bath' | 'drinks' | 'home' | 'accessories'
export type ProductForm = 'capsules' | 'tablets' | 'powder' | 'oil'
export type ProductKind = 'device' | 'supplement' | 'goods'

export interface ProductImage {
  src: string
  width: number
  height: number
}

export interface Product {
  id: string
  slug: string
  brandId: keyof typeof BRAND_LABELS
  name: string
  /** Фасовка только если она читается на упаковке или указана в материалах заказчика. */
  pack: string | null
  category: Category
  form: ProductForm | null
  kind: ProductKind
  image: ProductImage
  gallery: ProductImage[]
  /** ID позиции прайс-листа (src/data/priceList.ts); null — цены у товара нет. */
  priceListId: string | null
  /** Две цены: ₽ и PV. null — «Цена уточняется». */
  price: ProductPrice | null
  /** Полное описание дословно из документов заказчика (структурированно); null — текста пока нет. */
  description: ProductDescription | null
}

