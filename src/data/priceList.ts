export function priceListItem(id: string): PriceListItem | undefined {
  return PRICE_LIST.find((item) => item.id === id)
}

/** Цена для товара сайта по ID из прайса. Неизвестный ID — ошибка: тихо терять цену нельзя. */
export function priceFromList(id: string): ProductPrice {
  const item = priceListItem(id)
  if (!item) throw new Error(`Нет позиции прайса ${id}`)
  return { rub: item.rub, pv: item.pv }
}
